import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import { Resvg } from "@resvg/resvg-js";

const mark = readFileSync("branding/mark.svg", "utf8");
const wordmark = readFileSync("branding/wordmark.svg", "utf8");
const path = mark.match(/<path[^>]+d="([^"]+)"/)[1];

function render(svg, width) {
  return new Resvg(svg, {
    fitTo: { mode: "width", value: width },
    font: { loadSystemFonts: true },
  })
    .render()
    .asPng();
}

function icon({ signedOut, locked, beta, safari }) {
  const foreground = signedOut || safari ? "#000000" : "#ffffff";
  const background = signedOut ? "#ffffff" : "#000000";
  const tile = safari
    ? ""
    : `<rect x="1" y="1" width="62" height="62" rx="14" fill="${background}" stroke="#000000" stroke-width="2"/>`;
  const lock = locked
    ? '<circle cx="49" cy="49" r="13" fill="#ffffff" stroke="#000000" stroke-width="2"/><path d="M44 47v-4a5 5 0 0 1 10 0v4M43 47h12v10H43Z" fill="none" stroke="#000000" stroke-width="3" stroke-linejoin="round"/>'
    : "";
  const badge = beta
    ? `<circle cx="54" cy="10" r="7" fill="${foreground}"/><circle cx="54" cy="10" r="3" fill="${background}"/>`
    : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${tile}<g transform="translate(6 6) scale(.8125)"><path fill="${foreground}" fill-rule="evenodd" d="${path}"/></g>${lock}${badge}</svg>`;
}

const images = "apps/browser/src/images";
for (const name of readdirSync(images)) {
  const size = name.match(/^icon(\d+)/);
  if (!size || !name.endsWith(".png")) continue;
  const width = Number(size[1]) * (name.includes("@2x") ? 2 : 1);
  writeFileSync(
    join(images, name),
    render(
      icon({
        signedOut: name.includes("_gray"),
        locked: name.includes("_locked"),
        beta: name.includes("_beta"),
        safari: name.includes("_safari"),
      }),
      width,
    ),
  );
}

for (const [name, width] of [
  ["icon64.png", 64],
  ["chrome-icon128.png", 128],
  ["windows-icon300.png", 300],
]) {
  writeFileSync(join("apps/browser/store/icons", name), render(icon({}), width));
}

for (const [name, color] of [
  ["logo-dark@2x.png", "#000000"],
  ["logo-white@2x.png", "#ffffff"],
]) {
  writeFileSync(
    join("apps/browser/src/popup/images", name),
    render(wordmark.replaceAll("currentColor", color), 560),
  );
}

for (const [name, width] of [
  ["berry19.png", 19],
  ["berry38.png", 38],
]) {
  writeFileSync(join(images, name), render(icon({}), width));
}

writeFileSync("branding/icon.svg", icon({}));
writeFileSync("branding/icon.png", render(icon({}), 256));

for (const width of [44, 50, 150]) {
  writeFileSync(`apps/browser/store/windows/Assets/icon_${width}.png`, render(icon({}), width));
}

// Recreate supporting product illustrations from vectors in the same neutral palette.
for (const folder of ["health-tab", "at-risk-password-carousel"]) {
  for (const name of readdirSync(join(images, folder))) {
    if (!name.endsWith(".png")) continue;
    const target = join(images, folder, name);
    const original = readFileSync(target);
    const width = original.readUInt32BE(16);
    const height = original.readUInt32BE(20);
    const dark = name.includes("dark");
    const foreground = dark ? "#ffffff" : "#000000";
    const surface = dark ? "#171717" : "#ffffff";
    const muted = dark ? "#404040" : "#e5e5e5";
    const label = folder === "health-tab" ? "Vault health" : "Strong passwords";
    const background = name.includes("_bg_");
    const content = background
      ? `<circle cx="240" cy="160" r="120" fill="${muted}" opacity=".25"/>`
      : `<rect x="40" y="30" width="400" height="260" rx="20" fill="${surface}" stroke="${muted}" stroke-width="2"/><path d="M40 90h400" stroke="${muted}" stroke-width="2"/><text x="68" y="69" fill="${foreground}" font-family="sans-serif" font-size="20" font-weight="600">${label}</text><g transform="translate(365 46) scale(.4)"><path fill="${foreground}" fill-rule="evenodd" d="${path}"/></g>${[112, 164, 216].map((y) => `<rect x="64" y="${y}" width="352" height="40" rx="8" fill="${muted}" opacity=".45"/><circle cx="84" cy="${y + 20}" r="5" fill="${foreground}"/><rect x="104" y="${y + 15}" width="${120 - (y - 112) / 2}" height="10" rx="5" fill="${foreground}" opacity=".6"/><path d="m380 ${y + 15} 5 5-5 5" fill="none" stroke="${foreground}" stroke-width="2"/>`).join("")}`;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 480 320">${content}</svg>`;
    writeFileSync(target, render(svg, width));
  }
}
console.log("Generated Bytewarden toolbar, popup, Safari, and store assets.");
